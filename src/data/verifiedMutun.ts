export const VERIFIED_MUTUN_MAP: Record<MutunId, MutunDocument> = {
  tuhfa: VERIFIED_TUHFA_MATN,
  jazariyyah: VERIFIED_JAZARIYYAH_MATN,
};

export function buildMutunWitness(params: {
  id: string;
  matnId: MutunId;
  chapterNumber: number;
  verseNumbers: number[];
  highlightedPhrase: string;
  simpleExplanation: string;
}): MutunWitness {
  const doc = VERIFIED_MUTUN_MAP[params.matnId];
  const chapter = doc.chapters.find(
    (c) => c.chapterNumber === params.chapterNumber
  );
  const allVerses = doc.chapters.flatMap((c) => c.verses);
  const selectedVerses: MutunVerseEntry[] = params.verseNumbers
    .map((vNum) => allVerses.find((v) => v.verseNumber === vNum))
    .filter((v): v is MutunVerseEntry => Boolean(v));

  const minV = Math.min(...params.verseNumbers);
  const maxV = Math.max(...params.verseNumbers);
  const isContiguous =
    params.verseNumbers.length > 1 &&
    maxV - minV + 1 === params.verseNumbers.length;

  const verseIndicesLabel =
    params.verseNumbers.length === 1
      ? `البيت (${params.verseNumbers[0]})`
      : isContiguous
      ? `الأبيات (${minV} – ${maxV})`
      : `الأبيات (${params.verseNumbers.join('، ')})`;

  return {
    id: params.id,
    matnId: params.matnId,
    matnName: doc.title,
    chapterNumber: params.chapterNumber,
    chapterTitle: chapter?.title ?? '',
    verseNumbers: params.verseNumbers,
    verseIndicesLabel,
    verses: selectedVerses,
    highlightedPhrase: params.highlightedPhrase,
    simpleExplanation: params.simpleExplanation,
  };
}
